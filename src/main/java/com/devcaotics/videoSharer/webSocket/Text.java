
package com.devcaotics.videoSharer.webSocket;

public class Text{

    private String id;
    private String text;

    public void setId(String id){
        this.id = id;
    }

    public String getId(){
        return this.id;
    }

    public void setText(String text){
        this.text = text;
    }

    public String getText(){
        return this.text;
    }

}
